// Scans public/downloads (subfolders become categories, root files -> "Documents")
// and writes the Downloads-page manifest used by app/downloads/page.js.
const fs = require('fs');
const path = require('path');

const DL_DIR = path.join(process.cwd(), 'public', 'downloads');
const OUT_FILE = path.join(process.cwd(), 'data', 'generatedDownloads.js');

function humanize(str) {
  return str
    .replace(/[_-]+/g, ' ')
    .replace(/\s+/g, ' ')
    .trim()
    .replace(/\b\w/g, (c) => c.toUpperCase());
}

function humanSize(bytes) {
  if (bytes < 1024) return bytes + ' B';
  const units = ['KB', 'MB', 'GB'];
  let v = bytes / 1024;
  let u = 0;
  while (v >= 1024 && u < units.length - 1) {
    v /= 1024;
    u += 1;
  }
  return v.toFixed(v >= 10 ? 0 : 1) + ' ' + units[u];
}

// "IHAC - ISO 14001.jpg.jpeg" -> "IHAC - ISO 14001.jpeg" (drop doubled inner extension)
function stripInnerExt(name) {
  const parts = name.split('.');
  if (parts.length > 2 && parts[parts.length - 2].length <= 5) {
    parts.splice(parts.length - 2, 1);
  }
  return parts.join('.');
}

function walk(dir, base, out) {
  for (const entry of fs.readdirSync(dir, { withFileTypes: true }).sort((a, b) => a.name.localeCompare(b.name))) {
    if (entry.name.startsWith('.')) continue;
    const full = path.join(dir, entry.name);
    if (entry.isDirectory()) {
      walk(full, base, out);
    } else {
      out.push(path.relative(base, full).split(path.sep).join('/'));
    }
  }
}

const rels = [];
walk(DL_DIR, DL_DIR, rels);

const docs = rels.map((rel) => {
  const parts = rel.split('/');
  const file = parts.pop();
  const category = parts.length ? humanize(parts[0]) : 'Documents';
  const ext = path.extname(file).replace(/^\./, '');
  const stat = fs.statSync(path.join(DL_DIR, rel));
  return {
    name: humanize(path.basename(stripInnerExt(file), path.extname(file))),
    file: '/downloads/' + rel.split('/').map(encodeURIComponent).join('/'),
    category,
    format: ext.toUpperCase(),
    size: humanSize(stat.size),
    sizeBytes: stat.size,
  };
});

const categories = [...new Set(docs.map((d) => d.category))].map((name) => ({
  name,
  items: docs.filter((d) => d.category === name),
}));

const header = `// AUTO-GENERATED by scripts/generate-downloads.js - do not edit manually.
// Regenerated on every build/predev via the prebuild/predev hooks.
export const generatedDownloads = ${JSON.stringify({ categories }, null, 2)};
`;

fs.mkdirSync(path.dirname(OUT_FILE), { recursive: true });
fs.writeFileSync(OUT_FILE, header);
console.log(`Downloads manifest: ${docs.length} documents across ${categories.length} categories -> ${OUT_FILE}`);
