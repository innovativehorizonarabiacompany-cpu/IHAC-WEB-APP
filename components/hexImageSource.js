export function resolveDivisionImage(division, index, pool, creativePool) {
  if (division.icon === 'Cpu') return ITHRION_POOL[index % ITHRION_POOL.length];
  if (division.images && division.images.length) return division.images[index % division.images.length];
  if (division.icon === 'Palette') {
    if (creativePool && creativePool.length) return creativePool[index % creativePool.length];
    return CREATIVE_IMAGE;
  }
  const used = pool || HEX_IMAGE_POOL;
  return getImageUrl(used[index % used.length]);
}